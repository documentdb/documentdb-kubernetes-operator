# Mirrors api/v1/*_types.go into api/preview so the deprecated
# documentdb.io/preview CRD version keeps a schema identical to v1 (required
# by the CRD "strategy: None" conversion). Edit api/v1 only; this script is
# run by `make manifests`.
set -euo pipefail

cd "$(dirname "$0")/.."
src=api/v1
dst=api/preview
marker='// +kubebuilder:deprecatedversion:warning="documentdb.io/preview is deprecated; use documentdb.io/v1"'

for f in "$src"/*_types.go; do
  out="$dst/$(basename "$f")"
  {
    echo "// Code generated by hack/sync-preview-api.sh from $f. DO NOT EDIT."
    echo
    sed -e 's/^package v1$/package preview/' \
        -e "s|^// +kubebuilder:storageversion\$|$marker|" "$f"
  } > "$out"
  if ! grep -qF "$marker" "$out"; then
    echo "error: $f has no '// +kubebuilder:storageversion' marker to replace" >&2
    exit 1
  fi
done
